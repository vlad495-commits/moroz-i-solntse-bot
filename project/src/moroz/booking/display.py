        ('led маска и водород', 'Сочетание светового ухода за лицом с LED-маской и спокойной процедуры водородотерапии.'),
        ('led', 'Световая процедура ухода за кожей лица с LED-маской.'),
        ('коллагенарий', 'Световой уход за кожей красным светом без загара и ультрафиолета.'),
        ('коллариум', 'Процедура загара с ультрафиолетом и красными лампами.'),
        ('солярий', 'Загар с помощью ультрафиолетовых ламп. Длительность подбирает администратор по типу кожи и опыту загара.'),
        ('водород', 'Спокойная процедура отдыха с вдыханием водородсодержащей газовой смеси через носовую канюлю. Ощущения индивидуальны.'),
        ('прессотерап', 'Аппаратная процедура: манжеты последовательно наполняются воздухом и мягко сжимают тело.'),
        ('криокапсул', 'Короткая процедура воздействия холодом на тело. Лицо остаётся снаружи капсулы.'),
