def procedure_details(name: str) -> str:
    return (f'{service_display_name(name)}\n\n{procedure_description(name)}\n\n'
            'Перед посещением специалист уточнит цель и индивидуальные ограничения. '
            'При заболеваниях, беременности или недомогании возможность процедуры нужно согласовать со специалистом. '
            'Ощущения и результат индивидуальны.')
