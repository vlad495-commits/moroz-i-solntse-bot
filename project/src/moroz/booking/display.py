"""Client copy from the approved procedure knowledge; never changes provider data."""
import re


def asks_component_duration(text: str) -> bool:
    return bool(re.search(
        r'кажд\w*\s+(?:процедур|част|этап)|по отдельности|распредел\w*\s+времен|разбивк\w*\s+времен',
        text, re.I,
    ))


def service_display_name(name: str) -> str:
    name = " ".join(name.split())
    name = re.sub(r'"\s*([^"\n]+?)\s*"', r'«\1»', name)
    name = re.sub(r'\b(?:fresh|фреш)\s+(?:день|дня)\b', 'Фреш день', name, flags=re.I)
    name = re.sub(r'\bКОЛЛАГЕНАРИЙ\b', 'Коллагенарий', name)
    name = re.sub(r'\bколлариум\b', 'Коллариум', name, flags=re.I)
    return name


